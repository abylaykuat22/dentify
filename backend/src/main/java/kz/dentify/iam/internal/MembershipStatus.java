package kz.dentify.iam.internal;

/** Статус членства аккаунта в клинике (IAM-01): Приглашён, Активен, Отключён. */
public enum MembershipStatus {

	/** Приглашён, приглашение ещё не принято. */
	INVITED,

	/** Работает в клинике. */
	ACTIVE,

	/** Доступ к клинике отключён: войти в неё нельзя, сессии в ней завершены. */
	DISABLED

}
