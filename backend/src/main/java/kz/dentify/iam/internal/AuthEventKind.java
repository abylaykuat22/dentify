package kz.dentify.iam.internal;

/**
 * Вид события журнала входов ({@code auth_event.kind}). Каждая попытка входа даёт событие; смену и сброс пароля,
 * принятие приглашения и завершение сеанса администратором добавят их задачи.
 */
public enum AuthEventKind {

	/** Вход: пароль верный, сессия создана. */
	SIGN_IN,

	/** Выход из сессии. */
	SIGN_OUT,

	/**
	 * Неверный пароль. Без аккаунта — неизвестный логин: ответ пользователю тот же. Сюда же вход, у которого пароль
	 * сменили, пока он шёл.
	 */
	WRONG_PASSWORD,

	/**
	 * Блокировка после попыток: неверная попытка, которая закрыла вход на логин, и каждая попытка, отклонённая лимитом
	 * входа (429), пока вход закрыт.
	 */
	LOCKED_OUT,

	/** Пароль верный, но доступ отключён: аккаунт заблокирован или все его членства отключены. */
	ACCESS_DISABLED

}
