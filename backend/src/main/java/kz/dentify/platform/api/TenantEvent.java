package kz.dentify.platform.api;

import java.util.UUID;

/**
 * Событие о данных одной клиники. Событие модуля — record с {@code clinicId} — реализует этот интерфейс, и обработчик
 * ({@code @EventListener}, {@code @TransactionalEventListener}, {@code @ApplicationModuleListener}) выполняется в
 * контексте клиники события:
 * <ul>
 * <li>контекст той же клиники перенесён из публикующего потока — обработчик выполняется как есть;</li>
 * <li>контекст другой клиники — {@link IllegalStateException}: обработчик смешал бы данные двух клиник;</li>
 * <li>контекста нет, например публикацию переотправили после рестарта или асинхронный обработчик получил событие,
 * опубликованное без клиники, — контекст ставится из события до начала транзакции обработчика;</li>
 * <li>контекста нет, но событие опубликовано в транзакции без клиники, а обработчик синхронный: внутри этой транзакции
 * или {@code @TransactionalEventListener} после её завершения. Клиника ставится, только если обработчик открывает свою
 * транзакцию: {@code @ApplicationModuleListener} или {@code @Transactional(propagation = REQUIRES_NEW)}. Иначе —
 * {@link IllegalStateException}: сессия и соединение прежней транзакции без клиники ещё привязаны к потоку.</li>
 * </ul>
 * Событие без этого интерфейса обрабатывается в контексте публикующего потока, если он был.
 */
public interface TenantEvent {

	/** Клиника, к данным которой относится событие. */
	UUID clinicId();

}
