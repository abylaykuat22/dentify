package kz.dentify.platform.identity;

import java.util.List;
import java.util.UUID;

import org.jspecify.annotations.Nullable;

/**
 * Активные сессии аккаунта (PLT-04): их хранит Spring Session в Valkey с индексом по аккаунту. На этом строятся экран
 * активных сессий и принудительный выход.
 * <p>
 * Завершённая сессия гаснет сразу и необратимо: следующий запрос с её cookie получает 401 {@code error.session-expired}
 * с любого устройства, в том числе если в момент завершения шёл её запрос. Так деактивация сотрудника и смена пароля
 * гасят сессии аккаунта быстрее, чем за 5 секунд: iam вызывает {@link #terminateAll(UUID)} или
 * {@link #terminateOthers(UUID, String)}. Эти два гасят и сессии аккаунта со входом до вызова, которых нет в списке, —
 * по времени входа: вход, шедший одновременно и получивший время входа позже вызова, они не гасят. Поэтому iam вызывает
 * их после коммита деактивации или смены пароля, а вход после {@link AccountSignIn#signIn} перечитывает аккаунт
 * (docs/architecture.md, Активные сессии).
 * <p>
 * Id сессии в Valkey наружу не отдаётся: это пароль на время сессии. У каждой сессии есть открытый id
 * {@link AccountSession#id()} — хэш настоящего, по нему интерфейс и завершает сессию.
 */
public interface AccountSessions {

	/**
	 * Активные сессии аккаунта, сначала последние по активности.
	 *
	 * @param currentSessionId id сессии текущего запроса, чтобы пометить её; null — запрос не из сессии аккаунта
	 */
	List<AccountSession> list(UUID accountId, @Nullable String currentSessionId);

	/**
	 * Завершить одну сессию аккаунта по её открытому id.
	 *
	 * @return false, если у аккаунта нет такой сессии: чужая, уже завершённая или выдуманная
	 */
	boolean terminate(UUID accountId, String sessionId);

	/** Завершить все сессии аккаунта, в том числе текущую: деактивация, выход везде. Возвращает число завершённых. */
	int terminateAll(UUID accountId);

	/**
	 * Завершить все сессии аккаунта, кроме текущей: смена пароля, «Завершить все, кроме моей».
	 *
	 * @param currentSessionId настоящий id сессии, которую оставить
	 */
	int terminateOthers(UUID accountId, String currentSessionId);

	/**
	 * Завершить сессии аккаунта, в которых выбрана эта клиника: отключение членства в клинике (T-IAM-11). Работа того
	 * же человека в других клиниках и сессии без выбранной клиники остаются. Завершение то же, что у
	 * {@link #terminate}: отметка отзыва каждой такой сессии, затем удаление, следующий запрос с её cookie — 401.
	 * <p>
	 * Отметки аккаунта здесь нет: сессия, в которой клинику выберут одновременно с отключением (выбор прочитал членство
	 * до коммита, а записал клинику в сессию после поиска), этим вызовом не гаснет. Это закрывает перепроверка активного
	 * членства на каждом запросе (T-IAM-07, docs/architecture.md, Права). Поэтому iam вызывает метод после коммита
	 * отключения членства, как и {@link #terminateAll(UUID)}.
	 *
	 * @return число завершённых сессий
	 */
	int terminateInClinic(UUID accountId, UUID clinicId);

}
