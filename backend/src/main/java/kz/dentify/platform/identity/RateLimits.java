package kz.dentify.platform.identity;

import java.time.Duration;

import kz.dentify.platform.api.ErrorCodes;
import kz.dentify.platform.api.TooManyRequestsException;

/**
 * Лимиты частоты для входа и сброса пароля (PLT-05). Счётчики живут в Valkey и общие для всех экземпляров приложения;
 * логин, e-mail и IP в ключах только хэшем SHA-256. Превышение — {@link TooManyRequestsException}: ответ 429 с
 * {@code Retry-After}. Общий лимит API на сессию ставит фильтр платформы сам, модулям его вызывать не нужно.
 * <p>
 * Вход (iam, T-IAM-02):
 *
 * <pre>
 * rateLimits.checkLogin(login, request.getRemoteAddr());   // до проверки пароля: 429, даже если пароль верный
 * if (!passwordMatches) {
 *     boolean locked = rateLimits.recordLoginFailure(login); // + запись в журнал входов, locked — ещё и блокировка
 *     throw new UnauthorizedException(...);
 * }
 * rateLimits.resetLogin(login);
 * </pre>
 *
 * Каждая попытка после {@link #checkLogin} заканчивается {@link #recordLoginFailure} или {@link #resetLogin}, а если
 * пароль так и не проверен (429 предела одновременных хэшей) — {@link #abandonLogin}: проверка заранее занимает место
 * попытки в счётчике логина, чтобы одновременные попытки не прошли её разом. Попытка, которая не закончилась ни одним
 * из них (другое исключение между ними), считается неверной, пока не выйдет из 15-минутного окна. Отказ
 * {@link #checkLogin} журнал входов пишет только при {@link #firstLoginRejection}: отказ ничего не стоит нападающему, а
 * строка журнала — стоит.
 * <p>
 * Логин и e-mail приводятся к нижнему регистру без крайних пробелов; телефон вызывающий нормализует сам, как хранит.
 */
public interface RateLimits {

	/**
	 * Можно ли пробовать войти: логин не заблокирован и с одного IP не больше 30 попыток в минуту. Блокировка — 5
	 * неверных попыток на логин за любые 15 минут: после пятой вход на логин закрыт на 15 минут от неё. Попытка с IP
	 * засчитывается здесь. На логин здесь атомарно занимается место попытки: неверные и ещё идущие попытки логина за 15
	 * минут вместе не больше 5, поэтому шестая одновременная попытка, с любого IP, получает 429, не дожидаясь, пока
	 * первые пять закончатся. Неверной попытка становится в {@link #recordLoginFailure(String)}.
	 *
	 * @throws TooManyRequestsException код {@link ErrorCodes#TOO_MANY_LOGIN_ATTEMPTS} с числом минут до следующей
	 * попытки
	 */
	void checkLogin(String login, String clientIp);

	/**
	 * Засчитать неверную попытку входа на логин (место, занятое в {@link #checkLogin}, становится неверной попыткой);
	 * пятая за 15 минут закрывает вход на логин на 15 минут.
	 *
	 * @return true, если эта попытка закрыла вход: журнал входов пишет событие «Блокировка после попыток»
	 */
	boolean recordLoginFailure(String login);

	/**
	 * Успешный вход: счётчик неверных попыток логина обнуляется, место этой попытки освобождается. Места других ещё
	 * идущих попыток логина остаются.
	 */
	void resetLogin(String login);

	/**
	 * Попытка входа закончилась, не проверив пароль, — предел одновременных хэшей ответил 429: место, занятое в
	 * {@link #checkLogin}, освобождается, неверные попытки логина не трогаются. Без этого под нагрузкой на хэширование
	 * пять таких повторов закрыли бы вход на 15 минут без единого неверного пароля. Пароль не проверен, поэтому
	 * освобождённое место не даёт лишней проверки пароля. Только для такого исхода: попытка, прерванная другим
	 * исключением (пароль мог быть уже проверен), держит место до выхода из окна.
	 */
	void abandonLogin(String login);

	/**
	 * Отказ {@link #checkLogin} (429) — первый ли он на логин за время отказа: первый пишется в журнал входов, следующие —
	 * нет. Время отказа — его {@code Retry-After} (при блокировке — до её конца), но не меньше минуты. Без этого каждая
	 * отклонённая попытка — ничего не стоящая нападающему — писала бы строку в журнал входов чужого аккаунта и искала бы
	 * аккаунт в БД: сотни строк в минуту с одного IP. Одновременные отказы на один логин получают true ровно один раз.
	 *
	 * @param retryAfter через сколько можно повторить — из отказа
	 * @return true — первый отказ за время отказа: записать его в журнал входов
	 */
	boolean firstLoginRejection(String login, Duration retryAfter);

	/**
	 * Засчитать запрос сброса пароля на адрес: не больше 3 писем за любой час, отклонённые запросы не считаются.
	 * Считаются запросы на любой адрес, есть такой аккаунт или нет, поэтому ответ 429 не выдаёт, существует ли адрес.
	 *
	 * @throws TooManyRequestsException код {@link ErrorCodes#TOO_MANY_REQUESTS}
	 */
	void checkPasswordReset(String email);

}
